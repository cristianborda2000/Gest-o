const { test, expect } = require('@playwright/test');
const { mock, seed } = require('./mock-supabase');
const XLSX = require('../../app/assets/vendor/xlsx.full.min.js');
function excel() {
  const book = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(book, XLSX.utils.aoa_to_sheet([['Pessoa', 'Celular'], ['Ana & João', '11999991234'], ['Ana & João', '+55 11 99999-1234'], ['Inválida', '123']]), 'Contatos');
  return Buffer.from(XLSX.write(book, { type: 'buffer', bookType: 'xlsx' }));
}
for (const mobile of [false, true]) test(`Excel import and compact WhatsApp list ${mobile ? 'mobile' : 'desktop'}`, async ({ page }) => {
  if (mobile) await page.setViewportSize({ width: 390, height: 844 });
  await mock(page, { ...structuredClone(seed), clientes: [] });
  if (mobile) await page.getByRole('button', { name: 'Abrir menu', exact: true }).click();
  await page.locator('.nav [data-module="clientes"]').click();
  await page.getByLabel('Planilha de clientes').setInputFiles({ name: 'clientes.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: excel() });
  await page.getByLabel('Incluir contatos sem telefone').uncheck();
  await expect(page.getByText('1 prontos para importar', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Importar 1 clientes' }).click();
  await expect(page.locator('.clients-contact')).toHaveCount(1);
  await page.getByLabel('Sua mensagem').fill('Olá, {nome}!\nVamos conversar? & sim');
  const link = page.getByRole('link', { name: 'Abrir WhatsApp' });
  const href = await link.getAttribute('href');
  expect(new URL(href).pathname).toBe('/5511999991234');
  expect(new URL(href).searchParams.get('text')).toBe('Olá, Ana & João!\nVamos conversar? & sim');
  await expect(page.getByRole('list', { name: 'Lista de clientes' }).getByRole('listitem')).toHaveCount(1);
  await expect(page.locator('.clients-contact')).not.toContainText('Vamos conversar?');
  const details = await page.locator('.clients-contact-details').boundingBox();
  const action = await link.boundingBox();
  expect(action.x).toBeGreaterThan(details.x + details.width);
  expect(Math.abs(action.y + action.height / 2 - (details.y + details.height / 2))).toBeLessThan(5);
  await expect(link).toHaveAttribute('target', '_blank');
  const popupPromise = page.waitForEvent('popup');
  await page.context().route('https://wa.me/**', route => route.fulfill({ body: 'WhatsApp manual' }));
  await link.click();
  const popup = await popupPromise; await popup.close();
  expect(await page.evaluate(() => state.clientes[0].status)).toBe('Lead');
  await page.getByLabel('Sua mensagem').fill('  ');
  await expect(page.locator('[data-client-open]')).not.toHaveAttribute('href');
  await page.getByLabel('Buscar cliente').fill('Ana');
  await expect(page.locator('.clients-contact')).toHaveCount(1);
  await page.getByLabel('Sua mensagem').fill('Nova mensagem para {nome}');
  expect(new URL(await link.getAttribute('href')).searchParams.get('text')).toBe('Nova mensagem para Ana & João');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.reload();
  if (mobile) await page.getByRole('button', { name: 'Abrir menu', exact: true }).click();
  await page.locator('.nav [data-module="clientes"]').click();
  await expect(page.locator('.clients-contact')).toHaveCount(1);
  await page.screenshot({ path: test.info().outputPath('clients.png'), fullPage: true });
});

test('129 Excel rows: review both pages, import all 128 contacts and repair a missing phone', async ({ page }) => {
  await mock(page, { ...structuredClone(seed), clientes: [] });
  await page.locator('.nav [data-module="clientes"]').click();
  const book = XLSX.utils.book_new();
  const rows = [['Nome', 'Telefone'], ...Array.from({ length: 128 }, (_, i) => [`Pessoa ${i + 1}`, i % 2 ? 11999991234 : ''])];
  const tab = XLSX.utils.aoa_to_sheet(rows); tab.B129.z = '0.00E+00';
  XLSX.utils.book_append_sheet(book, tab, 'Clientes');
  const file = { name: '129-linhas.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: Buffer.from(XLSX.write(book, { type: 'buffer', bookType: 'xlsx' })) };
  await page.getByLabel('Planilha de clientes').setInputFiles(file);
  await expect(page.getByText('128 contatos encontrados', { exact: false })).toBeVisible();
  await expect(page.getByText('Página 1 de 2', { exact: false })).toBeVisible();
  await expect(page.locator('.clients-import-preview tbody tr')).toHaveCount(100);
  await page.getByRole('button', { name: 'Próxima', exact: true }).click();
  await expect(page.locator('.clients-import-preview tbody tr')).toHaveCount(28);
  await expect(page.getByRole('cell', { name: 'Pessoa 128', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Importar 128 clientes' }).click();
  await expect(page.locator('.clients-contact')).toHaveCount(128);
  await expect(page.locator('#clientsNotice')).toContainText('128 clientes importados, sendo 64 com telefone pendente');
  await expect(page.locator('[data-client-open][href]')).toHaveCount(64);
  const first = page.locator('.clients-contact').filter({ has: page.getByRole('heading', { name: 'Pessoa 1', exact: true }) });
  await expect(first.locator('[data-client-open]')).not.toHaveAttribute('href');
  await page.getByLabel('Planilha de clientes').setInputFiles(file);
  await expect(page.getByRole('button', { name: 'Importar 0 clientes', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Cancelar importação' }).click();
  await first.getByRole('button', { name: 'Corrigir telefone' }).click();
  await first.getByLabel('Telefone de Pessoa 1', { exact: true }).fill('21988887777');
  await first.getByRole('button', { name: 'Salvar telefone' }).click();
  await expect(first.getByRole('link', { name: 'Abrir WhatsApp' })).toHaveAttribute('href', /wa.me\/5521988887777/);
  await page.reload();
  await page.locator('.nav [data-module="clientes"]').click();
  await expect(page.locator('.clients-contact')).toHaveCount(128);
  await expect(page.locator('[data-client-open][href]')).toHaveCount(65);
});
